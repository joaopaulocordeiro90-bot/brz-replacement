import assert from 'node:assert/strict';
import {applyPaymentConfirmation,applyPaymentConfirmations,__test} from '../assets/secure/pagamento_confirmacoes.mjs';
assert.equal(__test.addDays('2026-11-09',30),'2026-12-09');
assert.equal(__test.addDays('2026-02-30',10),null);
const base={id:'nf990101_01',produto:'Farelo',modalidadeComercial:'CIF',pagamentoRegra:'10 dias (marco não informado)',preco:2090};
const confirmed=applyPaymentConfirmation(base,{legacy_id:base.id,payment_basis:'RETIRADA',payment_days:10});
assert.equal(confirmed.pagamentoRegra,'10 dias após cada retirada');
assert.equal(confirmed.pagamentoMarcoConfirmado,'RETIRADA');
assert.equal(base.pagamentoRegra,'10 dias (marco não informado)','Original untouched');
const first=applyPaymentConfirmation({id:'nf990101_02',modalidadeComercial:'CIF',pagamentoRegra:'30 dias (marco não informado)'},{legacy_id:'nf990101_02',payment_basis:'PRIMEIRA_ENTREGA',payment_days:30,first_delivery_date:'2026-11-09'});
assert.equal(first.pagamentoVencimentoIndicativo,'2026-12-09');
assert.match(first.pagamentoRegra,/primeira entrega/);
const d=applyPaymentConfirmation({id:'nf990101_03',modalidadeComercial:'FOB',pagamentoRegra:'10 dias (marco não informado)'},{legacy_id:'nf990101_03',payment_basis:'ENTREGA',payment_days:10});
assert.equal(d.pagamentoMarcoConfirmado,'ENTREGA','User override wins over FOB default');
const generic=applyPaymentConfirmation({id:'nf990101_04',modalidadeComercial:'FOB',pagamentoRegra:'15 dias (marco inicial não informado)'},null);
assert.equal(generic.pagamentoRegra,'15 dias após cada retirada');
const cif=applyPaymentConfirmation({id:'nf990101_05',modalidadeComercial:'CIF',pagamentoRegra:'30D (marco inicial não informado)'},null);
assert.equal(cif.pagamentoRegra,'30 dias após cada entrega');
const nf=applyPaymentConfirmation({id:'nf990101_06',modalidadeComercial:'CIF',pagamentoRegra:'30 dias após emissão da NF'},null);
assert.equal(nf.pagamentoRegra,'30 dias após emissão da NF','Explicit NF must prevail');
const wheat=applyPaymentConfirmation({id:'nf990101_07',preco:null,unidadePreco:'US$/t + CBS',precoMoeda:'USD'},{legacy_id:'nf990101_07',price_unit:'BRL_T'});
assert.equal(wheat.preco,null,'Numeric price must remain unknown');
assert.equal(wheat.unidadePreco,'US$/t + CBS','Do not overwrite conflicting original pricing');
assert.equal(wheat.precoUnidadeConfirmada,'R$/t');
assert.equal(wheat.precoUnidadeConflito,true);
assert.equal(applyPaymentConfirmations([base],[{legacy_id:base.id,payment_basis:'RETIRADA',payment_days:10}]).length,1);
console.log('F62: vencimentos e conflitos de unidades preservados.');
