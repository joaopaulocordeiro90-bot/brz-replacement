import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const patch=read('../assets/secure/f61_map_patch.js');
const main=read('../assets/js/part_06.js');
const report=read('../assets/js/part_17.js');
const leafletEvents=[];
function TileLayer(){this.events={};}
TileLayer.prototype.initialize=function(url,opts){this.url=url;this.options=opts;return this};
TileLayer.prototype.on=function(ev,fn){this.events[ev]=fn;return this};
TileLayer.prototype.setUrl=function(u){this.url=u;leafletEvents.push(u)};
const doc={readyState:'loading',addEventListener(){},getElementById(){return null}};
const ctx={window:{L:{TileLayer}},document:doc,console:{warn(){},error(){}},setTimeout(){},Object};
runInNewContext(patch,ctx);
const t=new TileLayer();
t.initialize('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png',{maxZoom:11});
assert.equal(t.options.subdomains,'abc','Leaflet uses subdomains.length even if URL has no {s}');
assert.equal(typeof t.options.subdomains.length,'number');
assert.match(t.url,/ArcGIS\/rest\/services\/World_Street_Map/);
t.events.tileerror();t.events.tileerror();
assert.match(t.url,/World_Topo_Map/,'Fallback must advance on tile failures');
assert.match(main,/function brzMapSafePortComparison\(d\)/,'Map calculations isolated per trade');
assert.match(main,/const batchSize=40/,'Map processing must be incremental');
assert.match(main,/showMapLayer\(\{\},\(\)=> '#bfc8c4'\)/,'Base map renders before calculations');
assert.match(main,/window\.__BRZ_MAP_RENDER_SEQUENCE/,'Stale render canceled');
assert.match(main,/safePanel\('Tabela','mapaTableBody'/,'Table cannot break map');
assert.match(report,/IntersectionObserver/,'Report lazy-loads hidden heavy tables');
assert.match(report,/function repF72RenderSection\(which\)/);
assert.match(report,/Tentar carregar novamente/,'Lazy errors recoverable');
assert.doesNotMatch(patch,/subdomains:undefined/);
console.log('F72: Leaflet subdomains, tile fallback, incremental map, isolated analytics, lazy Report passed.');
